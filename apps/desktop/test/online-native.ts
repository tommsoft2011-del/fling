import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { NativeSourcePicker, type NativeSourceMetadata } from '../src/native-source-picker';
let next: () => Promise<NativeSourceMetadata | null> = async () => null;
let calls = 0;
const picker = new NativeSourcePicker(async () => { calls++; return next(); });
assert.equal(await picker.pick(), null);
next = async () => { throw new Error('picker error'); };
await assert.rejects(picker.pick(), /picker error/);
next = async () => ({ sourceId: 'opaque-id', name: 'test.bin', size: 780 * 1024 * 1024 });
assert.deepEqual(await picker.pick(), { sourceId: 'opaque-id', name: 'test.bin', size: 817889280 });
let resolve!: (value: NativeSourceMetadata | null) => void;
next = () => new Promise((yes) => { resolve = yes; });
const pending = picker.pick();
assert.equal(await picker.pick(), null);
resolve(null); await pending;
assert.equal(calls, 4, 'concurrent picker invocation must be ignored');
next = async () => ({ sourceId: 'retry-id', name: 'again.bin', size: 0 });
assert.equal((await picker.pick())?.sourceId, 'retry-id');
console.log('ok - native picker mock: cancel, error, success, concurrent guard and retry');
const read = (file: string) => readFileSync(new URL(file, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const tasks = read('../src/tasks.ts');
const bridge = read('../src/online-rust.ts');
const main = read('../src-tauri/src/main.rs');
const transfer = read('../src-tauri/src/online_transfer.rs');
const session = read('../src-tauri/src/online_session.rs');
const source = read('../src-tauri/src/online_source.rs');
const nativeBranch = /if \(this.nativeSingleFile\) \{\n\s*\/\/ A single high-level command[\s\S]*?\n      \}/.exec(tasks)?.[0] ?? '';
assert.match(nativeBranch, /sendNativeSource\(this.source\[0\]!\.sourceId!\)/);
assert.doesNotMatch(nativeBranch, /sendFile\(|buildManifest|arrayBuffer|slice\(|sendTaskDone|waitForAck/);
const sourceSend = /async sendNativeSource[\s\S]*?\n  \}/.exec(bridge)?.[0] ?? '';
assert.match(sourceSend, /online_send_source/);
assert.doesNotMatch(sourceSend, /path|blob|Uint8Array|ensureFilePath/);
assert.match(bridge, /Legacy Blob compatibility[\s\S]*?NOT Rust-only/);
assert.match(main, /async fn online_pick_source[\s\S]*?spawn_blocking[\s\S]*?blocking_pick_file/);
assert.match(source, /source.owner != owner/);
assert.match(source, /source.expires <= Instant::now\(\)/);
assert.ok(source.replace(/\s+/g, '').includes('source.file.try_clone()'));
const commit = /pub async fn check_complete[\s\S]*?pub fn target_path/.exec(transfer)?.[0] ?? '';
assert.ok(commit.indexOf('file.flush()') < commit.indexOf('file.sync_all()'));
assert.ok(commit.indexOf('file.sync_all()') < commit.indexOf('disk.read'));
assert.ok(commit.indexOf('digest != self.manifest.sha256') < commit.indexOf('std::fs::hard_link'));
const ack = /async fn maybe_ack[\s\S]*?\/\/\/ Receiver: a P2P offer/.exec(session)?.[0] ?? '';
assert.ok(ack.indexOf('receiver.check_complete()') < ack.indexOf('chunk_ack_message'));
assert.match(ack, /for attempt in 0\.\.3/);
assert.match(ack, /publish_progress_ack\(receiver, &self\.receiver_last_ack, next_seq, self\.room\.send\(&ack\)\)/);
assert.doesNotMatch(ack, /insert\(id, next_seq\)/, 'no unconditional per-frame ACK cursor update');
const cursorWrite = ack.indexOf('self.receiver_last_ack.lock().await.insert');
assert.ok(cursorWrite > ack.indexOf('if !published'), 'final cursor follows successful ACK publication');
assert.ok(cursorWrite < ack.indexOf('status.stage = "done"'), 'completion follows successful final ACK');
const progressAck = /async fn publish_progress_ack[\s\S]*?\/\/\/ Events emitted/.exec(session)?.[0] ?? '';
assert.ok(progressAck.indexOf('return Ok(false)') < progressAck.indexOf('publish.await?'));
assert.ok(progressAck.indexOf('publish.await?') < progressAck.indexOf('last_acks.lock().await.insert'));
assert.match(session, /native_single_file != Some\(true\)/);
assert.match(read('../src/taskcard.ts'), /activityBytes > 0 && idleMs > 15000/);
console.log('ok - sourceId-only high-level UI boundary, legacy isolation, durable commit/ACK order and pre-progress UI guards (static)');
console.log('ok - production ACK cursor advances only after publish; skipped frames accumulate toward threshold (static)');
console.log('These mocks/contracts are not native picker GUI or two-machine Windows validation.');
